import nunjucks from "nunjucks";
import { readdir, readFile, mkdir, writeFile, cp, rm } from "node:fs/promises";
import { join, relative } from "node:path";
async function files(dir: string): Promise<string[]> {
  return (
    await Promise.all(
      (await readdir(dir, { withFileTypes: true })).map((e) =>
        e.isDirectory() ? files(join(dir, e.name)) : [join(dir, e.name)],
      ),
    )
  ).flat();
}
await mkdir("src/workers/generated", { recursive: true });
const entries = [];
for (const file of await files("core/templates")) {
  if (!file.endsWith(".html")) continue;
  const name = relative("core/templates", file);
  const code = nunjucks.precompileString(await readFile(file, "utf8"), {
    name,
    wrapper: (templates: any) => templates[0].template,
  } as any);
  entries.push(`${JSON.stringify(name)}: (() => {${code}})()`);
}
await writeFile(
  "src/workers/generated/templates.js",
  `// Generated by scripts/workers/build.ts\nexport default {${entries.join(",\n")}};\n`,
);
await rm("dist/assets", { recursive: true, force: true });
await mkdir("dist/assets/static", { recursive: true });
await cp("core/static", "dist/assets/static", { recursive: true });
console.log(`Precompiled ${entries.length} templates and copied assets.`);
